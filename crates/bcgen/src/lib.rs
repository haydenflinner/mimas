/// The `B*` branch family — `right` for the register variant, `imm` for the
/// immediate one (`is_float` picks the `f64::from_bits` decode). A mismatched
/// operand type pre-advances `code.ip` and tail-calls the `branch_cold*`
/// helper the interpreter's own macro would have reached.
#[allow(clippy::too_many_arguments)]
fn emit_branch(
    s: &mut String,
    sh: &Sh,
    off: usize,
    next: usize,
    target: &BlockTarget,
    left: Reg,
    right: Option<Reg>,
    imm: Option<(i64, bool)>,
    is_true: bool,
    variant: &str,
    op: &str,
    binop: &str,
    tail: &dyn Fn(usize) -> String,
) {
    let t = tgt(target);
    let int = variant == "Val::Int";
    let hit = if let Some(r) = right {
        let cold = format!(
            "return branch_cold(regs, code, {t}, {is_true}, {}, {}, ctx, BinOp::{binop});",
            reg(left),
            reg(r)
        );
        let a = if int {
            int_opnd(sh, left, next, off, &cold)
        } else {
            float_opnd(sh, left, next, off, &cold)
        };
        let b = if int {
            int_opnd(sh, r, next, off, &cold)
        } else {
            float_opnd(sh, r, next, off, &cold)
        };
        format!("{a} {op} {b}")
    } else if let Some((val, true)) = imm {
        let cold = format!(
            "return branch_cold_imm_float(regs, code, {t}, {is_true}, {}, f64::from_bits({val}i64 as u64), ctx, BinOp::{binop});",
            reg(left)
        );
        let a = float_opnd(sh, left, next, off, &cold);
        format!("{a} {op} f64::from_bits({val}i64 as u64)")
    } else {
        let (val, _) = imm.unwrap();
        let cold = format!(
            "return branch_cold_imm_int(regs, code, {t}, {is_true}, {}, {val}i64, ctx, BinOp::{binop});",
            reg(left)
        );
        let a = int_opnd(sh, left, next, off, &cold);
        format!("{a} {op} {val}i64")
    };
    let _ = writeln!(s, "let hit = {hit};");
    let _ = writeln!(
        s,
        "if hit == {is_true} {{ {} }} else {{ {} }}",
        tail(t),
        tail(next)
    );
}
